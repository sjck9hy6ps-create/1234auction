CREATE FUNCTION pg_temp.fix_region(r text, d text) RETURNS text LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN r NOT IN ('경북 의성군', '경북 청송군', '경북 영양군', '경북 영덕군', '경북 청도군', '경북 고령군', '경북 성주군', '경북 칠곡군', '경북 예천군', '경북 봉화군', '경북 울진군', '경북 울릉군', '경남 고성군', '경남 남해군', '경남 하동군', '경남 산청군', '경남 함양군', '경남 거창군', '경남 합천군') THEN r
    WHEN left(r, 2) = '경북' AND split_part(d, ' ', 1) = '북면' THEN
      CASE WHEN split_part(d, ' ', 2) IN ('천부리', '현포리', '나리') THEN '경북 울릉군' ELSE '경북 울진군' END
    ELSE COALESCE((SELECT county FROM em_map WHERE prov = left(r, 2) AND em = split_part(d, ' ', 1)), r)
  END
$$;

